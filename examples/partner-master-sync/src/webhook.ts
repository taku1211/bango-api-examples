import { createServer, type IncomingHttpHeaders, type Server } from 'node:http';
import { isUtf8 } from 'node:buffer';
import type { DatabaseSync } from 'node:sqlite';
import { Webhook, WebhookVerificationError } from 'standardwebhooks';
import { storeEvent, transaction, validEvent } from './core.ts';

const SIGNED_HEADER_NAMES = ['webhook-id', 'webhook-timestamp', 'webhook-signature'] as const;

export class InvalidWebhookBodyError extends Error {
  constructor() {
    super('verified webhook body is not valid JSON');
    this.name = 'InvalidWebhookBodyError';
  }
}

function sdkHeaders(headers: IncomingHttpHeaders): Record<string, string> {
  return Object.fromEntries(SIGNED_HEADER_NAMES.map((name) => {
    const value = headers[name];
    return [name, typeof value === 'string' ? value : ''];
  }));
}

function createVerifiers(secrets: string | readonly string[]): Webhook[] {
  const configuredSecrets = typeof secrets === 'string' ? [secrets] : secrets;
  if (configuredSecrets.length === 0) throw new Error('at least one webhook secret is required');
  return configuredSecrets.map((secret) => new Webhook(secret));
}

function verifyWithVerifiers(
  verifiers: readonly Webhook[],
  body: Buffer,
  headers: IncomingHttpHeaders,
): unknown {
  // The SDK computes the signed text after decoding a Buffer as UTF-8. Reject malformed byte
  // sequences first so distinct raw bodies cannot normalize to the same signed string.
  if (!isUtf8(body)) throw new WebhookVerificationError('body is not valid UTF-8');
  const signedHeaders = sdkHeaders(headers);
  for (const verifier of verifiers) {
    try {
      return verifier.verify(body, signedHeaders);
    } catch (error) {
      if (error instanceof WebhookVerificationError) continue;
      if (error instanceof SyntaxError) throw new InvalidWebhookBodyError();
      throw error;
    }
  }
  throw new WebhookVerificationError('no configured secret verified the message');
}

export function verifyBangoWebhook(
  secrets: string | readonly string[],
  body: Buffer,
  headers: IncomingHttpHeaders,
): unknown {
  // Let invalid configured keys fail as server configuration errors instead of treating them
  // as an untrusted sender's bad signature.
  return verifyWithVerifiers(createVerifiers(secrets), body, headers);
}

// Offline demo helper only. Compatibility fixtures in tests are generated by Bango's signer.
export function signDemo(secret: string, payload: object, nowMillis = Date.now()) {
  const id = (payload as { id?: string }).id;
  if (!id) throw new Error('payload.id required');
  const timestamp = String(Math.floor(nowMillis / 1000));
  const body = Buffer.from(JSON.stringify(payload));
  const signature = new Webhook(secret).sign(id, new Date(Number(timestamp) * 1000), body);
  return { body, headers: {
    'content-type': 'application/json',
    'webhook-id': id,
    'webhook-timestamp': timestamp,
    'webhook-signature': signature,
  } };
}

export function createReceiver(db: DatabaseSync, secrets: string | readonly string[], allowedSubjectId?: string): Server {
  // Construct once so an invalid key is reported before the server accepts requests.
  const verifiers = createVerifiers(secrets);

  return createServer(async (req, res) => {
    if (req.url !== '/webhooks/demo') { res.writeHead(404).end(); return; }
    if (req.method !== 'POST') { res.writeHead(405).end(); return; }
    try {
      const chunks: Buffer[] = [];
      let size = 0;
      for await (const chunk of req) {
        const bytes = Buffer.from(chunk);
        size += bytes.length;
        if (size > 64 * 1024) { res.writeHead(413).end(); return; }
        chunks.push(bytes);
      }
      const raw = Buffer.concat(chunks);
      let payload: unknown;
      try {
        payload = verifyWithVerifiers(verifiers, raw, req.headers);
      } catch (error) {
        if (error instanceof WebhookVerificationError) { res.writeHead(401).end(); return; }
        if (error instanceof InvalidWebhookBodyError) { res.writeHead(400).end(); return; }
        throw error;
      }
      if (!payload || typeof payload !== 'object' || Array.isArray(payload)) {
        res.writeHead(400).end(); return;
      }
      const { id, type } = payload as { id?: unknown; type?: unknown };
      if (id !== req.headers['webhook-id'] || typeof type !== 'string') {
        res.writeHead(400).end(); return;
      }
      if (type === 'endpoint.test') {
        // A connectivity test has no business snapshot and must not update a master.
        res.writeHead(200).end(); return;
      }
      if (!validEvent(payload)) { res.writeHead(400).end(); return; }
      if (allowedSubjectId !== undefined && payload.subject.id !== allowedSubjectId) { res.writeHead(400).end(); return; }
      // Acknowledge only after a durable inbox transaction commits.
      transaction(db, () => storeEvent(db, payload));
      res.writeHead(200).end();
    } catch {
      // Do not log the body, signature, URL secret, or database credentials.
      res.writeHead(500).end();
    }
  });
}
